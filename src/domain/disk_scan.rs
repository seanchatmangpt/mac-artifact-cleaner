// ── Backup triplication (nominate keep-newest) ─────────────────────────────────

/// Nominate-only class: same-day, same-size tarball triplication (witnessed:
/// erlmcp backups — three copies of the same archive written the same day).
/// Returns the paths to nominate for deletion — **all but the newest** of each
/// `(size, day)` group. `--aggressive` gates actual deletion; the nomination
/// itself always fires so the plan records the duplication.
///
/// Entries are `(path, size_bytes, mtime_epoch_secs)`.
///
/// # Examples
///
/// ```
/// use osx_clnr::domain::disk_scan::triplicate_nominate;
/// use std::path::PathBuf;
///
/// // Three same-day, same-size erlmcp tarballs; the 14:00 one is newest.
/// let day = 1_760_000_000; // any epoch base; day bucketing is internal
/// let backups = vec![
///     (PathBuf::from("/b/erlmcp-a.tar.gz"), 1_073_741_824, day),
///     (PathBuf::from("/b/erlmcp-b.tar.gz"), 1_073_741_824, day + 3600),
///     (PathBuf::from("/b/erlmcp-c.tar.gz"), 1_073_741_824, day + 7200),
/// ];
/// let kill = triplicate_nominate(&backups);
/// assert_eq!(kill.len(), 2);
/// assert!(kill.contains(&PathBuf::from("/b/erlmcp-a.tar.gz")));
/// assert!(!kill.contains(&PathBuf::from("/b/erlmcp-c.tar.gz")));
///
/// // Negative: differing sizes are distinct archives — nothing nominated.
/// let distinct = vec![
///     (PathBuf::from("/b/a.tar.gz"), 100, day),
///     (PathBuf::from("/b/b.tar.gz"), 200, day),
/// ];
/// assert!(triplicate_nominate(&distinct).is_empty());
///
/// // Refusal: a single archive is never nominated.
/// assert!(triplicate_nominate(&[(PathBuf::from("/b/solo.tar.gz"), 5, day)]).is_empty());
/// ```
pub fn triplicate_nominate(entries: &[(PathBuf, u64, i64)]) -> Vec<PathBuf> {
    use std::collections::HashMap;
    let mut groups: HashMap<(u64, i64), Vec<usize>> = HashMap::new();
    for (i, (_, size, mtime)) in entries.iter().enumerate() {
        groups.entry((*size, mtime / 86_400)).or_default().push(i);
    }
    let mut kill = Vec::new();
    for mut idxs in groups.into_values() {
        if idxs.len() < 2 {
            continue;
        }
        idxs.sort_by_key(|&i| entries[i].2);
        for &i in &idxs[..idxs.len() - 1] {
            kill.push(entries[i].0.clone());
        }
    }
    kill
}

// ── Operator-call classes (nominate-only, never auto) ──────────────────────────

/// True when `reason` names an operator-call class: nominated for human review
/// only, never eligible for auto-approval. Each class needs an action outside
/// the scanner's authority:
///
/// - `colima datadisk`: in-VM prune needs `colima stop` + disk compact.
/// - `model weights`: public HF/ollama weights re-download on demand.
/// - `simulator devices`: `xcrun simctl` device state, not plain files.
/// - `installer`: Downloads installers — user confirms re-download.
/// - `history giant blob`: rewriting git history invalidates SHAs/receipts.
/// - `stale archive`: root-level archives the operator may still want.
///
/// # Examples
///
/// ```
/// use osx_clnr::domain::disk_scan::is_operator_call_reason;
///
/// assert!(is_operator_call_reason("colima datadisk (needs stop+compact)"));
/// assert!(is_operator_call_reason("model weights (repullable)"));
/// assert!(is_operator_call_reason("simulator devices (CoreSimulator)"));
/// assert!(is_operator_call_reason("installer dmg (Downloads, 200 MB)"));
/// assert!(is_operator_call_reason("history giant blob (rewrites SHAs)"));
/// assert!(is_operator_call_reason("stale archive (988 MB, 200d)"));
/// assert!(!is_operator_call_reason("rust target"));
/// assert!(!is_operator_call_reason("node dependencies"));
/// ```
pub fn is_operator_call_reason(reason: &str) -> bool {
    const OPS: [&str; 6] = [
        "colima datadisk",
        "model weights",
        "simulator devices",
        "installer",
        "history giant blob",
        "stale archive",
    ];
    OPS.iter().any(|op| reason.contains(op))
}

/// Operator-call class gate: a Downloads installer (`*.dmg`/`*.pkg`) larger
/// than 100 MB (witnessed class `installer_dmg`).
///
/// # Examples
///
/// ```
/// use osx_clnr::domain::disk_scan::is_installer_dmg;
/// use std::path::Path;
///
/// assert!(is_installer_dmg(Path::new("/Users/j/Downloads/Xcode_16.dmg"), 200_000_000));
/// // Too small.
/// assert!(!is_installer_dmg(Path::new("/Users/j/Downloads/notes.dmg"), 5_000_000));
/// // Wrong extension.
/// assert!(!is_installer_dmg(Path::new("/Users/j/Downloads/big.zip"), 200_000_000));
/// ```
pub fn is_installer_dmg(path: &Path, size_bytes: u64) -> bool {
    let ext = path.extension().map(|e| e.to_string_lossy().to_lowercase()).unwrap_or_default();
    matches!(ext.as_str(), "dmg" | "pkg") && size_bytes > 100 * 1024 * 1024
}

/// Operator-call class gate: a home-root-level archive larger than 500 MB
/// whose mtime is older than 6 months (witnessed: `Archive 3.zip` 988 MB,
/// `backup-critical` 1.3 GB). Nominate-only: the operator decides.
///
/// "Home-root-level" means directly in `$HOME` or in Downloads/Desktop/
/// Documents — not buried in a project tree.
///
/// # Examples
///
/// ```
/// use osx_clnr::domain::disk_scan::is_stale_archive;
/// use std::path::Path;
///
/// assert!(is_stale_archive(Path::new("/Users/j/Archive 3.zip"), 988 * 1024 * 1024, 200));
/// assert!(is_stale_archive(Path::new("/Users/j/Downloads/backup-critical.tar.gz"), 1_300_000_000, 365));
/// // Too small.
/// assert!(!is_stale_archive(Path::new("/Users/j/small.zip"), 100 * 1024 * 1024, 200));
/// // Too recent.
/// assert!(!is_stale_archive(Path::new("/Users/j/Archive 3.zip"), 988 * 1024 * 1024, 30));
/// // Buried in a project tree — out of scope.
/// assert!(!is_stale_archive(Path::new("/Users/j/proj/old/archives/x.zip"), 988 * 1024 * 1024, 200));
/// ```
pub fn is_stale_archive(path: &Path, size_bytes: u64, age_days: i64) -> bool {
    let ext = path.extension().map(|e| e.to_string_lossy().to_lowercase()).unwrap_or_default();
    let name = path.file_name().map(|n| n.to_string_lossy().to_lowercase()).unwrap_or_default();
    let ext = if name.ends_with(".tar.gz") { "tar.gz".to_string() } else { ext };
    let root_level = path.parent().is_some_and(|p| {
        p == Path::new("/")
            // directly inside a home dir (`/Users/<name>`)
            || p.parent() == Some(Path::new("/Users"))
            || p.file_name()
                .is_some_and(|f| f == "Downloads" || f == "Desktop" || f == "Documents")
    });
    matches!(ext.as_str(), "zip" | "tar.gz" | "tgz" | "7z")
        && size_bytes > 500 * 1024 * 1024
        && age_days > 180
        && root_level
}

