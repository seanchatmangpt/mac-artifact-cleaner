//! Disk-scan-derived classifier classes (CLASSIFIER_REVISION r7).
//!
//! Encodes the 2026-10-08 15-lane disk-scan nomination corpus as pure domain
//! predicates. All functions are pure: they take inert snapshots/primitives
//! and touch no filesystem — the integration layer supplies mtimes, sizes,
//! and child listings via `EntrySnapshot`/`DirSnapshot` and stat data.
//!
//! Two policy tiers:
//! - **Reversible (auto)**: safe to fold into a plan's auto-approve tier.
//! - **Operator-call**: `nominate-only`, never auto-deleted; each item needs an
//!   action outside the scanner's authority (in-VM prune, model repull,
//!   SHA-invalidating history rewrite, user re-download).

use std::path::{Path, PathBuf};

use crate::domain::artifact::{Candidate, DirSnapshot};

// ── TCC gate ───────────────────────────────────────────────────────────────────

/// Returns true when `path` is inside a TCC-protected subtree the process
/// cannot read (e.g. `~/Library/Mail`, `~/.Trash`). Callers must **skip and
/// report** these, never error and never retry — an unreadable path is not
/// evidence of absence of candidates, it is a bounded gap in coverage.
///
/// # Examples
///
/// ```
/// use osx_clnr::domain::disk_scan::is_tcc_gate_path;
/// use std::path::Path;
///
/// // Positive: unreadable-without-consent subtrees are gated.
/// assert!(is_tcc_gate_path(Path::new("/Users/j/Library/Mail")));
/// assert!(is_tcc_gate_path(Path::new("/Users/j/Library/Mail/V9")));
/// assert!(is_tcc_gate_path(Path::new("/Users/j/.Trash/junk")));
///
/// // Negative: scannable tool roots are not gated.
/// assert!(!is_tcc_gate_path(Path::new("/Users/j/Library/Caches/go-build")));
/// assert!(!is_tcc_gate_path(Path::new("/Users/j/proj/target")));
/// ```
pub fn is_tcc_gate_path(path: &Path) -> bool {
    let s = path.to_string_lossy();
    s.contains("/Library/Mail") || s.ends_with("/.Trash") || s.contains("/.Trash/")
}

// ── Reversible (auto) classes ──────────────────────────────────────────────────

/// Reversible class: a repo-root `erl_crash.dump` (witnessed: erlmcp-style
/// roots accumulate large crash dumps at the project root). Diagnostics
/// output of a past crash — not an input to anything; rebuildable by
/// absence. Extends the erlang-project-scoped rule already in
/// `artifact_candidates_from_snapshot` to any root.
///
/// # Examples
///
/// ```
/// use osx_clnr::domain::disk_scan::erl_crash_dump_candidate;
/// use osx_clnr::domain::artifact::{DirSnapshot, EntryKind, EntrySnapshot};
/// use std::path::{Path, PathBuf};
///
/// let snap = DirSnapshot {
///     children: vec![EntrySnapshot::new(
///         PathBuf::from("/repo/erl_crash.dump"),
///         "erl_crash.dump".into(),
///         Some("dump".into()),
///         EntryKind::File,
///     )],
/// };
/// // Positive: root-level crash dump is nominated.
/// let c = erl_crash_dump_candidate(Path::new("/repo"), &snap).unwrap();
/// assert_eq!(c.path, PathBuf::from("/repo/erl_crash.dump"));
/// assert_eq!(c.reason, "erlang crash dump (repo root)");
///
/// // Negative: no dump, no nomination.
/// assert!(erl_crash_dump_candidate(Path::new("/repo"), &DirSnapshot::default()).is_none());
/// ```
pub fn erl_crash_dump_candidate(root: &Path, snap: &DirSnapshot) -> Option<Candidate> {
    if snap.has_file("erl_crash.dump") {
        return Some(Candidate {
            path: root.join("erl_crash.dump"),
            reason: "erlang crash dump (repo root)".to_string(),
        });
    }
    None
}

/// Reversible class: `ios/build` and `ios/Pods` under a project root that has
/// a `Podfile.lock` (witnessed: zoela, 6.8 GB). Both are regenerated by
/// `xcodebuild`/`pod install` from the lockfile.
///
/// # Examples
///
/// ```
/// use osx_clnr::domain::disk_scan::ios_build_pods_candidates;
/// use osx_clnr::domain::artifact::{DirSnapshot, EntryKind, EntrySnapshot};
/// use std::path::{Path, PathBuf};
///
/// let snap = DirSnapshot {
///     children: vec![
///         EntrySnapshot::new(PathBuf::from("/z/Podfile.lock"), "Podfile.lock".into(), Some("lock".into()), EntryKind::File),
///         EntrySnapshot::new(PathBuf::from("/z/ios"), "ios".into(), None, EntryKind::Dir),
///     ],
/// };
/// // Positive: both regenerable subtrees are nominated.
/// let c = ios_build_pods_candidates(Path::new("/z"), &snap);
/// assert_eq!(c.len(), 2);
/// assert!(c.iter().any(|x| x.path == PathBuf::from("/z/ios/build")));
/// assert!(c.iter().any(|x| x.path == PathBuf::from("/z/ios/Pods")));
///
/// // Negative: no Podfile.lock → no nomination (an ios/ dir alone is not signal).
/// let no_lock = DirSnapshot {
///     children: vec![EntrySnapshot::new(PathBuf::from("/z/ios"), "ios".into(), None, EntryKind::Dir)],
/// };
/// assert!(ios_build_pods_candidates(Path::new("/z"), &no_lock).is_empty());
///
/// // Negative: lockfile but no ios/ dir → nothing to nominate.
/// let no_ios = DirSnapshot {
///     children: vec![EntrySnapshot::new(PathBuf::from("/z/Podfile.lock"), "Podfile.lock".into(), Some("lock".into()), EntryKind::File)],
/// };
/// assert!(ios_build_pods_candidates(Path::new("/z"), &no_ios).is_empty());
/// ```
pub fn ios_build_pods_candidates(root: &Path, snap: &DirSnapshot) -> Vec<Candidate> {
    let mut out = Vec::new();
    if snap.has_file("Podfile.lock") && snap.has_dir("ios") {
        for rel in ["build", "Pods"] {
            out.push(Candidate {
                path: root.join("ios").join(rel),
                reason: "ios build/pods (regenerable from Podfile.lock)".to_string(),
            });
        }
    }
    out
}

/// Reversible class decision: a vendored `node_modules` is stale when its
/// upstream mtime/commit is older than 2 years (class
/// `node_modules_stale_vendor`).
///
/// # Examples
///
/// ```
/// use osx_clnr::domain::disk_scan::node_modules_stale;
///
/// // Positive: 3-year-old vendored tree is stale.
/// assert!(node_modules_stale(3 * 365 * 86_400));
///
/// // Negative: fresh vendored tree is not.
/// assert!(!node_modules_stale(86_400));
///
/// // Refusal boundary: exactly 2 years is not yet stale.
/// assert!(!node_modules_stale(2 * 365 * 86_400));
/// ```
pub fn node_modules_stale(age_secs: i64) -> bool {
    age_secs > 2 * 365 * 86_400
}

/// Reversible class decision for `venv_stale`: a `.venv` is nominatable only
/// when BOTH (a) no doc reference exists — the README/CLAUDE/justfile/AGENTS
/// grep IS the documented-toolchain gate — AND (b) last use is older than 30
/// days. A documented venv is a KEEP regardless of age (witnessed: autofde
/// documented-KEEP vs mfw stale).
///
/// # Examples
///
/// ```
/// use osx_clnr::domain::disk_scan::venv_stale;
///
/// // Positive: unreferenced + 45d unused → nominate.
/// assert!(venv_stale(false, 45));
///
/// // Negative: documented toolchain → KEEP even at 2 years.
/// assert!(!venv_stale(true, 730));
///
/// // Negative: recent use → keep.
/// assert!(!venv_stale(false, 3));
///
/// // Refusal boundary: exactly 30d is not yet stale.
/// assert!(!venv_stale(false, 30));
/// ```
pub fn venv_stale(doc_referenced: bool, last_use_age_days: u64) -> bool {
    !doc_referenced && last_use_age_days > 30
}

/// Reversible class: orphaned `node_modules` — a `node_modules` directory with
/// no package manifest (`package.json`, `package-lock.json`, `yarn.lock`,
/// `pnpm-lock.yaml`, `bun.lockb`) in its enclosing manifest scope. Witnessed:
/// a stray `~/node_modules` (1.9 GB) with no manifest anywhere near it.
///
/// `snap` is the listing of the nearest enclosing directory that could hold
/// the manifest; the caller walks up to find that scope.
///
/// # Examples
///
/// ```
/// use osx_clnr::domain::disk_scan::is_orphan_node_modules;
/// use osx_clnr::domain::artifact::{DirSnapshot, EntryKind, EntrySnapshot};
/// use std::path::PathBuf;
///
/// // Positive: node_modules present, no manifest anywhere in scope.
/// let snap = DirSnapshot {
///     children: vec![EntrySnapshot::new(PathBuf::from("/h/node_modules"), "node_modules".into(), None, EntryKind::Dir)],
/// };
/// assert!(is_orphan_node_modules(&snap));
///
/// // Negative: package.json sibling → legitimate dependency tree.
/// let owned = DirSnapshot {
///     children: vec![
///         EntrySnapshot::new(PathBuf::from("/h/package.json"), "package.json".into(), Some("json".into()), EntryKind::File),
///         EntrySnapshot::new(PathBuf::from("/h/node_modules"), "node_modules".into(), None, EntryKind::Dir),
///     ],
/// };
/// assert!(!is_orphan_node_modules(&owned));
///
/// // Negative: lockfile-only scope (manifest regenerated elsewhere) still owns it.
/// let locked = DirSnapshot {
///     children: vec![
///         EntrySnapshot::new(PathBuf::from("/h/pnpm-lock.yaml"), "pnpm-lock.yaml".into(), Some("yaml".into()), EntryKind::File),
///         EntrySnapshot::new(PathBuf::from("/h/node_modules"), "node_modules".into(), None, EntryKind::Dir),
///     ],
/// };
/// assert!(!is_orphan_node_modules(&locked));
/// ```
pub fn is_orphan_node_modules(snap: &DirSnapshot) -> bool {
    snap.has_dir("node_modules")
        && !snap.has_file("package.json")
        && !snap.has_file("package-lock.json")
        && !snap.has_file("yarn.lock")
        && !snap.has_file("pnpm-lock.yaml")
        && !snap.has_file("bun.lockb")
}

/// Reversible class: lane build roots under `$TMPDIR` or `~/.cache/tmp`
/// (witnessed: `~/.cache/tmp/base-2/runs/x/_build`, 2.6 GB across xaas
/// roots). Extends the `_build-lane*` fan-out lease rule: a build-root-named
/// directory living under a `tmp` component is scratch, not a live lease —
/// tmp regimes are scrubbed wholesale, so nothing canonical lives there.
///
/// # Examples
///
/// ```
/// use osx_clnr::domain::disk_scan::is_tmp_lane_build_root;
/// use std::path::Path;
///
/// // Positive: build roots under tmp scratch areas.
/// assert!(is_tmp_lane_build_root(Path::new("/Users/j/.cache/tmp/base-2/runs/x/_build")));
/// assert!(is_tmp_lane_build_root(Path::new("/private/tmp/laneA/_build-laneW984dj")));
/// assert!(is_tmp_lane_build_root(Path::new("/var/folders/aa/T/target")));
///
/// // Negative: the canonical checkout's own build dirs are NOT tmp roots.
/// assert!(!is_tmp_lane_build_root(Path::new("/Users/j/xaas/_build")));
/// assert!(!is_tmp_lane_build_root(Path::new("/Users/j/xaas/_build-laneX")));
/// assert!(!is_tmp_lane_build_root(Path::new("/Users/j/osx-clnr/target")));
///
/// // Refusal: no tmp component → out of scope for this class.
/// assert!(!is_tmp_lane_build_root(Path::new("/Users/j/proj/deps")));
/// ```
pub fn is_tmp_lane_build_root(path: &Path) -> bool {
    let comps: Vec<&str> = path.components().filter_map(|c| c.as_os_str().to_str()).collect();
    let under_tmp = comps.iter().any(|c| *c == "tmp" || *c == "T");
    if !under_tmp {
        return false;
    }
    let last = comps.last().copied().unwrap_or("");
    crate::domain::artifact::is_artifact_leaf_name(last)
}

/// Reversible class: git's interrupted-repack temporaries —
/// `.git/objects/pack/tmp_pack_*` (witnessed: `tmp_pack_QIkM2S`, 607 MB).
/// A `tmp_pack_*` survives only a crashed/interrupted `git gc`/fetch; git
/// never reads it back and recreates it on the next repack.
///
/// # Examples
///
/// ```
/// use osx_clnr::domain::disk_scan::is_tmp_pack_file;
/// use std::path::Path;
///
/// assert!(is_tmp_pack_file(Path::new("/Users/j/erlmcp/.git/objects/pack/tmp_pack_QIkM2S")));
///
/// // Negative: real pack files are not temporaries.
/// assert!(!is_tmp_pack_file(Path::new("/Users/j/erlmcp/.git/objects/pack/pack-abc123.pack")));
///
/// // Negative: a tmp_pack outside .git is out of scope.
/// assert!(!is_tmp_pack_file(Path::new("/Users/j/tmp/tmp_pack_QIkM2S")));
/// ```
pub fn is_tmp_pack_file(path: &Path) -> bool {
    path.to_string_lossy().contains("/.git/objects/pack/tmp_pack_")
}

// ── Reversible (auto): Electron HTTP caches ────────────────────────────────────

/// Reversible class: Electron app-bundle HTTP caches — `Cache/`,
/// `Code Cache/`, `GPUCache/` directories inside an `.app` bundle.
/// **Refusal**: if a `Service Worker/` directory is a sibling (same parent),
/// the nomination is refused — deleting the HTTP cache while a service worker
/// holds registrations corrupts the app's offline state; the operator must
/// clear the family together via the app itself.
///
/// # Examples
///
/// ```
/// use osx_clnr::domain::disk_scan::{is_electron_http_cache_dir, electron_cache_refused};
/// use std::path::Path;
///
/// // Positive: HTTP-cache dirs inside an app bundle.
/// assert!(is_electron_http_cache_dir(Path::new(
///     "/Applications/Zed.app/Contents/Resources/app/Cache"
/// )));
/// assert!(is_electron_http_cache_dir(Path::new(
///     "/Applications/Zed.app/Contents/Resources/app/Code Cache"
/// )));
/// assert!(is_electron_http_cache_dir(Path::new(
///     "/Applications/Zed.app/Contents/Resources/app/GPUCache"
/// )));
///
/// // Negative: an arbitrary Cache dir outside an .app bundle is out of scope.
/// assert!(!is_electron_http_cache_dir(Path::new("/Users/j/proj/Cache")));
///
/// // Refusal: a Service Worker sibling refuses the nomination.
/// assert!(electron_cache_refused(Path::new("/App/Z.app/Contents/a/Cache"), true));
/// assert!(!electron_cache_refused(Path::new("/App/Z.app/Contents/a/Cache"), false));
/// ```
pub fn is_electron_http_cache_dir(path: &Path) -> bool {
    let name = path.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default();
    let in_app = path.components().any(|c| c.as_os_str().to_string_lossy().ends_with(".app"));
    in_app && matches!(name.as_str(), "Cache" | "Code Cache" | "GPUCache")
}

/// Refusal half of the Electron HTTP-cache class: a `Service Worker/` sibling
/// refuses the whole nomination (see `is_electron_http_cache_dir`).
pub fn electron_cache_refused(path: &Path, has_service_worker_sibling: bool) -> bool {
    has_service_worker_sibling && is_electron_http_cache_dir(path)
}

